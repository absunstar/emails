'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('site_files/js/app.js', 'utf8');
const start = source.indexOf('SBUI.dateTime = function (value) {');
const end = source.indexOf('\n    };', start);
assert(start > 0 && end > start, 'Shared date-time formatter must be present');
const factory = '(function () {const SBUI={}; '+source.slice(start, end + 7)+';return SBUI.dateTime;})()';
const dateTime = vm.runInNewContext(factory, {Intl, Date, String, Number, document:{documentElement:{lang:'ar'}}});
const date = '2026-10-25T02:07:57Z';
const clean = text => text.replace(/[\u200e\u200f\u061c\u202a-\u202e\u2066-\u2069]/g, '').replace(/\s+/g,' ');
const arabic = clean(dateTime(date));
assert(/25\/10\/2026/.test(arabic), 'Arabic UI should show day/month/year in local order: '+arabic);
assert(/[0-9]/.test(arabic) && !/[٠-٩]/.test(arabic), 'Date numbers should stay Latin');
const englishFormatter = vm.runInNewContext(factory, {Intl, Date, String, Number, document:{documentElement:{lang:'en'}}});
assert.equal(englishFormatter(date), new Date(date).toLocaleString(), 'English date formatting must remain backward compatible');
assert.equal(dateTime('not-date'), 'not-date');
assert.equal(dateTime(null), '');
console.log('Localized message dates and English default: PASS');
