const { englishTemplate } = require('./render-english-template');
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const html = englishTemplate(fs.readFileSync('apps/emails/site_files/html/free.html', 'utf8'));
const js = fs.readFileSync('apps/emails/site_files/js/index.js', 'utf8');
const workspace = html.indexOf('<div class="mail-workspace">');
const main = html.indexOf('<div class="mailbox-main">', workspace);
const sidebar = html.indexOf('<aside class="mailbox-sidebar"', main);
const grid = html.indexOf('<div class="mail-address-grid">', main);
const inbox = html.indexOf('<div class="inbox-panel">', grid);
const ecosystem = html.indexOf('<section class="quick-mail-ecosystem"', inbox);
const manage = html.indexOf('<button class="quick-mail-manage-toggle"', ecosystem);
assert(main > workspace && sidebar > main && grid > main && inbox > grid && ecosystem > inbox && manage > ecosystem && sidebar > manage, 'Quick email and inbox must precede all promotions and mobile saved-mail controls');
const controls = html.slice(grid, html.indexOf('</div>\n<div class="quick-mail-steps"', grid));
const field = controls.indexOf('data-mail-address');
const copy = controls.indexOf('data-action="copy-email"');
const generate = controls.indexOf('data-action="generate-email"');
const qr = controls.indexOf('data-action="show-qr"');
assert(field >= 0 && copy > field && generate > copy && qr > generate, 'Email field and primary copy button must precede secondary actions');
assert.match(html, /<span class="quick-mail-overline">QUICK MAIL[\s\S]*?BY EGYTAG/);
assert.match(html, /https:\/\/emails\.egytag\.com\//);
assert.doesNotMatch(html.slice(0, html.indexOf('</head>')), /https:\/\/emails\.social-browser\.com\//);
assert.match(html, /Private inboxes are exclusive to the Android app Pro upgrade/);
for (const link of ['android_play','android_apk','social_browser','egytag_tools']) assert(html.includes('data-quick-mail-link="'+link+'"'), 'Missing conversion CTA: '+link);
assert.match(html, /@media\(max-width:820px\)[\s\S]*?\.quick-mail-js \.mailbox-sidebar\{display:none!important\}/);
assert.match(html, /\.quick-mail-js \.mailbox-sidebar\.is-open\{display:flex!important\}/);
assert.match(js, /root\.classList\.add\('quick-mail-js'\)/);
assert.match(js, /if \(action === 'toggle-saved-inboxes'\)/);
for (const event of ['temp_mail_created','temp_mail_copied','temp_mail_inbox_checked','temp_mail_android_play_click','temp_mail_android_apk_click','temp_mail_social_browser_click','temp_mail_egytag_tools_click']) assert(js.includes("'"+event+"'"), 'Missing analytics event '+event);
assert.match(js, /if \(typeof window\.gtag === 'function'\)[^\n]*product: 'egytag_temp_mail'/);
assert.doesNotMatch(js, /trackQuickMailEvent\([^)]*,/);
console.log('Quick Mail 2.0 feature, responsive layout and anonymous conversion events passed');
